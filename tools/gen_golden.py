def tm_vals(v):
    return "%s, %s, %s, %s, %s, %s, %s, %s, %s, 0x%x, %s" % (v["h"], v["a"], v["d"], v["il"], v["el"], v["ave"], v["max"], v["wt"], v["oh"],
                                                         int(v["pf"], 0), v["cs"])


def tm_text(v):
    return "GetTextFace `%s`; TEXTMETRIC h/a/d/il/el/ave/max = %s/%s/%s/%s/%s/%s/%s; weight %s, overhang %s, pitch/family %s, charset %s" % (
        v["got"], v["h"], v["a"], v["d"], v["il"], v["el"], v["ave"], v["max"], v["wt"], v["oh"], v["pf"], v["cs"])


STOCK_C = {"OEM_FIXED_FONT", "ANSI_FIXED_FONT", "ANSI_VAR_FONT", "SYSTEM_FONT", "DEVICE_DEFAULT_FONT", "SYSTEM_FIXED_FONT", "DEFAULT_GUI_FONT"}


def gen_font_metrics(tabs, check, results):
    area = "golden_font_metrics"
    b1 = [r for r in tabs["B1"].rows if ascii_face(r.k["face"]) and r.v["got"] is not None and r.v["h"] is not None]
    b2 = [r for r in tabs["B2"].rows if ascii_face(r.k["face"]) and r.v["got"] is not None and r.v["h"] is not None]
    b3 = [r for r in tabs["B3"].rows if r.k["via"] == "stock" and r.k["obj"] in STOCK_C]
    s1, s2, s3 = pick(b1, QUOTA["B1"]), pick(b2, QUOTA["B2"]), pick(b3, QUOTA["B3"])
    nrows = len(s1) + len(s2) + len(s3)
    c = [BANNER % dict(title="font metrics: face x size -> TEXTMETRIC", probe="probes/font_metrics", nrows=nrows), FM_HEAD]
    ev = []
    c.append("/* B1 regular weight (%d rows) and B2 bold / italic at UI heights (%d rows) */" % (len(s1), len(s2)))
    c.append("static const tm_row TM[] = {")
    for rows in (s1, s2):
        for r in rows:
            k, v = r.k, r.v
            c.append("    { %s,\n      %s, %s, %s, %s, %s, %s, %s }," % (cstr(r.src), wstr(k["face"]), k["req_h"], k["wt"], k["it"], k["cs"],
                                                                      wstr(v["got"]), tm_vals(v)))
            ev.append(("golden_fm_textmetric_by_face_and_size", r.src, tm_text(v)))
    c.append("};\n")
    c.append("/* B3 stock fonts (%d rows) */" % len(s3))
    c.append("static const stock_row STOCK[] = {")
    for r in s3:
        c.append("    { %s,\n      %s, %s, %s }," % (cstr(r.src), r.k["obj"], wstr(r.v["got"]), tm_vals(r.v)))
        ev.append(("golden_fm_stock_fonts", r.src, tm_text(r.v)))
    c.append("};\n")
    c.append(FM_T1)
    c.append(FM_T2)
    write(os.path.join(TESTS, area, area + ".c"), "\n".join(c), check, results)
    write(os.path.join(TESTS, area, "EVIDENCE.md"),
          evidence(area, "font metrics", "Tables B1, B2 and B3 of `docs/D12_DECISION_DATA.md` (recording family `font_metrics`, "
                   "`data/win10/font_metrics/README.md`: two fresh boots identical, 96 DPI). golden_fm_textmetric_by_face_and_size creates a LOGFONTW "
                   "(recorded face, height, weight, italic, charset; default quality, default pitch, don't-care family), selects it into the screen DC "
                   "(MM_TEXT) and compares GetTextFace and eleven TEXTMETRIC fields. golden_fm_stock_fonts does the same for the stock fonts "
                   "(GetStockObject, the `via=stock` rows).", ev), check, results)
    return nrows


# ------------------------------------------------------------------ golden_char_widths
CW_C = r"""
#define NROWS(a) ((int)(sizeof(a) / sizeof((a)[0])))

typedef struct { unsigned short c; short w; } cw_t;

/* One face/height with the recorded advance (GetCharWidth32W) of each character. */
typedef struct { const char *src; const WCHAR *face; int h; const cw_t *w; int n; } cwrow;

/* One face/height with the recorded GetTextExtentPoint32W width of some strings. */
typedef struct { const WCHAR *text; short cx; } ext_t;
typedef struct { const char *src; const WCHAR *face; int h; const ext_t *e; int n; } extrow;

static HFONT cw_font(const WCHAR *face, int h){
    LOGFONTW lf; memset(&lf, 0, sizeof lf);
    lf.lfHeight = h; lf.lfWeight = FW_NORMAL; lf.lfCharSet = DEFAULT_CHARSET;
    lstrcpynW(lf.lfFaceName, face, LF_FACESIZE);
    return U(CreateFontIndirectW)(&lf);
}

static void cw_run(const cwrow *rows, int nrows){
    HDC dc = U(GetDC)(NULL);
    REQUIRE(dc);
    for (int i = 0; i < nrows; i++) {
        const cwrow *r = &rows[i];
        HFONT f = cw_font(r->face, r->h);
        CHECKF(f != NULL, "%s: CreateFontIndirectW failed", r->src);
        if (!f) continue;
        HGDIOBJ old = U(SelectObject)(dc, f);
        for (int j = 0; j < r->n; j++) {
            INT w = -1;
            BOOL ok = U(GetCharWidth32W)(dc, r->w[j].c, r->w[j].c, &w);
            CHECKF(ok && w == r->w[j].w, "%s: width of U+%04X is %d want %d", r->src, r->w[j].c, (int)w, r->w[j].w);
        }
        U(SelectObject)(dc, old);
        U(DeleteObject)(f);
    }
    U(ReleaseDC)(NULL, dc);
}
"""

