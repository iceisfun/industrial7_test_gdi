#!/usr/bin/env python3
"""gen_golden.py - generate the golden conformance tests tests/golden_<family>/ from the decision tables.

    python3 tools/gen_golden.py            # (re)writes tests/golden_*/golden_*.c and EVIDENCE.md
    python3 tools/gen_golden.py --check    # exit 1 when a generated file differs from the committed one

The rows come from tools/gen_d12.py (docs/D12_DECISION_DATA.md), i.e. from the committed Windows 10 recordings in
data/win10, nothing else. Each generated area asserts a SAMPLE of those rows against the live system through the
public API, black-box (no gdi32 link; U(Name)); on the Windows 10 22H2 guest the recordings come from they pass by
construction. The tests call the same API sequence as the recording probe (probes/<family>), so a row passes exactly
when the system makes the decision that was recorded.

Sampling rule (the only selection logic, applied per table, in table order, deterministic):
    0. DPI values below 96 are never asserted (volatile, see EVIDENCE.md of golden_ui_metrics).
    1. keep only rows the test can state in C (ASCII face names of at most 31 characters without quote or backslash);
    2. take N rows evenly spaced over the kept rows: kept[(i * len(kept)) // N] for i in 0..N-1 (the first row is always
       taken, duplicates removed); N is the QUOTA entry of the table below;
    3. grouped rows (A4 charsets, A5 pitch/family) assert the first and the last member of each chosen group (A5: the
       first); pivot rows (D1, D2, D4) assert every cell of the chosen row; the per-DPI UI font and non-client rows (B4, B5)
       are all taken for the four sources caption, menu, message and icon title at the five SystemParametersInfoForDpi
       DPIs 96..192.
Rows asserted in total: printed by the generator and listed per area in tests/golden_*/EVIDENCE.md.
"""
