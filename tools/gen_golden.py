TESTS = os.path.join(ROOT, "tests")

QUOTA = {"A1": 40, "A2": 8, "A4": 14, "A5": 6, "B1": 60, "B2": 20, "B3": 7, "C1": 8, "C2": 3, "C3": 6, "D1": 12, "D2": 5,
         "D4": 6}


def pick(items, n):
    out, seen = [], set()
    if not items:
        return out
    for i in range(n):
        j = (i * len(items)) // n
        if j not in seen:
            seen.add(j)
            out.append(items[j])
    return out


def ascii_face(f):
    return len(f) <= 31 and all(0x20 <= ord(c) < 0x7F and c not in '"\\' for c in f)


def cstr(s):
    assert all(0x20 <= ord(c) < 0x7F for c in s), s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def wstr(s):
    return "L" + cstr(s)


def opt_w(s):
    return "NULL" if s is None else wstr(s)


def num(x):
    return "0" if x is None else str(int(x, 0)) if isinstance(x, str) else str(x)


def hexv(x):
    return "0x%x" % int(x, 0)


# ------------------------------------------------------------------ file skeleton
BANNER = """/* GENERATED by tools/gen_golden.py from the decision tables (tools/gen_d12.py, docs/D12_DECISION_DATA.md). Do not edit.
 * Golden area: %(title)s.
 * Every row below is one recording row of the committed Windows 10 22H2 recordings; the `src` string names the file and
 * the row key. The test calls the public API the way the recording probe (%(probe)s) did and compares the result.
 * Black-box: nothing links against the DLL under test (U(Name)). Rows asserted: %(nrows)d (see EVIDENCE.md). */
#include "t.h"
"""


def write(path, text, check, results):
    cur = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    results.append((path, cur == text))
    if check:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if cur != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def evidence(area, title, intro, rows, extra=""):
    """rows: [(id, test, src, asserted)]"""
    o = ["# tests/%s: evidence" % area, "",
         "Area: %s. Generated by `tools/gen_golden.py` together with `%s.c`; do not edit by hand." % (title, area), "",
         "Oracle: Windows 10 22H2 (10.0.19045.2965), en-US, 96 DPI system DPI, the guest the recordings were made on. "
         "Every expectation below is a recording row (source kind **rec**): the value in the recording is the value the test asserts. "
         "No expectation was invented or changed; no assertion is conditional on the result (a missing export skips the test with a reason). "
         "The rows were chosen by the sampling rule of `tools/gen_golden.py` (even spacing over the rows of the table, quota per table).", "",
         intro, ""]
    if extra:
        o += [extra, ""]
    o += ["| # | test | recording row (`<file> <table>:<key>`) | asserted |", "|---|---|---|---|"]
    for i, (t, src, asserted) in enumerate(rows, 1):
        o.append("| %d | %s | `%s` | %s |" % (i, t, src.replace("|", "\\|"), asserted))
    return "\n".join(o) + "\n"


# ------------------------------------------------------------------ golden_face_substitution
def member_rows(grow):
    return grow.extra["rows"]


FS_COMMON = r"""
#define NROWS(a) ((int)(sizeof(a) / sizeof((a)[0])))

/* One request (LOGFONT: height, weight 400, charset, pitch/family, face) and the recorded decision. */
typedef struct {
    const char *src;     /* recording file + row key */
    const WCHAR *face;   /* requested lfFaceName */
    int h, cs, pf;       /* lfHeight, lfCharSet, lfPitchAndFamily */
    const WCHAR *got;    /* GetTextFaceW */
    const WCHAR *fam;    /* OUTLINETEXTMETRIC family name; NULL: raster/vector or not recorded */
    int tmcs, tmpf;      /* TEXTMETRIC tmCharSet, tmPitchAndFamily */
    int th, ta, td;      /* tmHeight, tmAscent, tmDescent; -1: not part of this table */
} fs_row;

static void fs_check(HDC dc, const fs_row *r){
    LOGFONTW lf; memset(&lf, 0, sizeof lf);
    lf.lfHeight = r->h; lf.lfWeight = FW_NORMAL; lf.lfCharSet = (BYTE)r->cs; lf.lfPitchAndFamily = (BYTE)r->pf;
    lstrcpynW(lf.lfFaceName, r->face, LF_FACESIZE);
    HFONT f = U(CreateFontIndirectW)(&lf);
    CHECKF(f != NULL, "%s: CreateFontIndirectW failed", r->src);
    if (!f) return;
    HGDIOBJ old = U(SelectObject)(dc, f);
    WCHAR got[LF_FACESIZE * 2] = L"";
    int n = U(GetTextFaceW)(dc, LF_FACESIZE * 2, got);
    CHECKF(n > 0 && !lstrcmpW(got, r->got), "%s: GetTextFace \"%ls\" want \"%ls\"", r->src, got, r->got);
    TEXTMETRICW tm; memset(&tm, 0, sizeof tm);
    CHECKF(U(GetTextMetricsW)(dc, &tm), "%s: GetTextMetricsW failed", r->src);
    CHECKF(tm.tmCharSet == r->tmcs, "%s: tmCharSet %d want %d", r->src, tm.tmCharSet, r->tmcs);
    CHECKF(tm.tmPitchAndFamily == r->tmpf, "%s: tmPitchAndFamily 0x%x want 0x%x", r->src, tm.tmPitchAndFamily, r->tmpf);
    if (r->th >= 0) {
        CHECKF(tm.tmHeight == r->th, "%s: tmHeight %ld want %d", r->src, tm.tmHeight, r->th);
        CHECKF(tm.tmAscent == r->ta, "%s: tmAscent %ld want %d", r->src, tm.tmAscent, r->ta);
        CHECKF(tm.tmDescent == r->td, "%s: tmDescent %ld want %d", r->src, tm.tmDescent, r->td);
    }
    if (r->fam) {
        UINT need = U(GetOutlineTextMetricsW)(dc, 0, NULL);
        CHECKF(need > 0, "%s: GetOutlineTextMetricsW size 0", r->src);
        if (need > 0 && need < 100000) {
            OUTLINETEXTMETRICW *o = (OUTLINETEXTMETRICW *)calloc(1, need);
            if (o && U(GetOutlineTextMetricsW)(dc, need, o)) {
                const WCHAR *fam = (const WCHAR *)((const char *)o + (size_t)o->otmpFamilyName);
                CHECKF(!lstrcmpW(fam, r->fam), "%s: OTM family \"%ls\" want \"%ls\"", r->src, fam, r->fam);
            }
            free(o);
        }
    }
    U(SelectObject)(dc, old);
    U(DeleteObject)(f);
}

static void fs_run(const fs_row *rows, int n){
    HDC dc = U(GetDC)(NULL);
    REQUIRE(dc);
    for (int i = 0; i < n; i++) fs_check(dc, &rows[i]);
    U(ReleaseDC)(NULL, dc);
}
"""


def fs_entry(r, with_metrics):
    v, k = r.v, r.k
    fam = v["otm_family"] if v["type"] == "tt" else None
    th = (v["h"], v["a"], v["d"]) if with_metrics else ("-1", "-1", "-1")
    return "    { %s,\n      %s, %s, %s, 0x%x, %s, %s, %s, 0x%x, %s, %s, %s }," % (
        cstr(r.src), wstr(k["face"]), k["req_h"], k["req_cs"], int(k["req_pf"], 0), wstr(v["got"]), opt_w(fam), v["cs"], int(v["pf"], 0),
        th[0], th[1], th[2])


def check_plain(r):
    k = r.k
    return (k["req_w"] == "0" and k["req_wt"] == "400" and k["req_it"] == "0" and k["req_op"] == "0" and k["req_cp"] == "0x0"
            and k["req_q"] == "0" and k["req_esc"] == "0" and k["req_ori"] == "0" and k["dc"] == "screen" and k["gm"] == "1"
            and k["api"] == "W" and r.v["got"] is not None)


def gen_face_substitution(tabs, check, results):
    area = "golden_face_substitution"
    a1 = [r for r in tabs["A1"].rows if ascii_face(r.k["face"]) and check_plain(r)]
    a2 = [r for r in tabs["A2"].rows if ascii_face(r.k["face"]) and check_plain(r)]
    a4 = [g for g in tabs["A4"].rows if ascii_face(g.k["face"]) and all(check_plain(m) for m in member_rows(g))]
    a5 = [g for g in tabs["A5"].rows if ascii_face(g.k["face"]) and all(check_plain(m) for m in member_rows(g))]
    s1 = pick(a1, QUOTA["A1"])
    s2 = pick(a2, QUOTA["A2"])
    s4 = []
    for g in pick(a4, QUOTA["A4"]):
        ms = member_rows(g)
        for m in ([ms[0], ms[-1]] if len(ms) > 1 else ms):
            if m not in s4:
                s4.append(m)
    s5 = [member_rows(g)[0] for g in pick(a5, QUOTA["A5"])]
    parts = {"a1": s1, "a2": s2, "a4": s4, "a5": s5}
    nrows = sum(len(v) for v in parts.values())
    c = [BANNER % dict(title="face substitution: requested face, charset, pitch/family -> realised face", probe="probes/face_substitution",
                       nrows=nrows), FS_COMMON]
    ev = []
    desc = {"a1": ("A1 requested face -> realised face (lfHeight -11, DEFAULT_CHARSET, metrics included)", True),
            "a2": ("A2 charset-specific registry substitutes", False),
            "a4": ("A4 requested charset -> realised face (first and last charset of each chosen group)", False),
            "a5": ("A5 requested pitch/family -> realised face (first value of each chosen group)", False)}
    for key in ("a1", "a2", "a4", "a5"):
        title, wm = desc[key]
        c.append("/* %s: %d rows */" % (title, len(parts[key])))
        c.append("static const fs_row %s[] = {" % key.upper())
        for r in parts[key]:
            c.append(fs_entry(r, wm))
            ev.append((key, r.src, "GetTextFace `%s`%s; tmCharSet %s; tmPitchAndFamily %s%s" % (
                r.v["got"], "; OTM family `%s`" % r.v["otm_family"] if r.v["type"] == "tt" else "", r.v["cs"], r.v["pf"],
                "; tmHeight/Ascent/Descent %s/%s/%s" % (r.v["h"], r.v["a"], r.v["d"]) if wm else "")))
        c.append("};")
        c.append("")
    c.append("""TEST(golden_fs_requested_face){
    /* A1: an installed face is realised as itself, an unknown face as Arial, MS Shell Dlg as Microsoft Sans Serif, ... */
    fs_run(A1, NROWS(A1));
}

TEST(golden_fs_registry_substitutes_by_charset){
    /* A2 */
    fs_run(A2, NROWS(A2));
}

TEST(golden_fs_charset_selects_face){
    /* A4 */
    fs_run(A4, NROWS(A4));
}

TEST(golden_fs_pitch_family_selects_face){
    /* A5: an installed face keeps its face for most values; an absent face follows the family (e.g. FF_ROMAN -> Times New Roman) */
    fs_run(A5, NROWS(A5));
}
""")
    write(os.path.join(TESTS, area, area + ".c"), "\n".join(c), check, results)
    write(os.path.join(TESTS, area, "EVIDENCE.md"),
          evidence(area, "face substitution", "Tables A1, A2, A4 and A5 of `docs/D12_DECISION_DATA.md` (recording family `face_substitution`, "
                   "`data/win10/face_substitution/README.md`: two fresh boots identical). Tests: golden_fs_requested_face (A1), "
                   "golden_fs_registry_substitutes_by_charset (A2), golden_fs_charset_selects_face (A4), "
                   "golden_fs_pitch_family_selects_face (A5). The request is a LOGFONTW with weight 400 and the "
                   "recorded height, charset and pitch/family, created with CreateFontIndirectW and selected into the screen DC.",
                   [({"a1": "golden_fs_requested_face", "a2": "golden_fs_registry_substitutes_by_charset",
                      "a4": "golden_fs_charset_selects_face", "a5": "golden_fs_pitch_family_selects_face"}[k], s, a)
                    for k, s, a in ev]),
          check, results)
    return nrows


# ------------------------------------------------------------------ golden_font_metrics
FM_HEAD = r"""
#define NROWS(a) ((int)(sizeof(a) / sizeof((a)[0])))

/* A request (LOGFONT: height, weight, italic, charset; default quality, default pitch, don't-care family) and the recorded TEXTMETRIC. */
typedef struct {
    const char *src;
    const WCHAR *face; int h, wt, it, cs;
    const WCHAR *got;                       /* GetTextFaceW */
    int th, ta, td, il, el, ave, max, tmwt, oh, pf, tmcs;
} tm_row;

/* A stock font (GetStockObject index) and the recorded TEXTMETRIC. */
typedef struct {
    const char *src;
    int obj;
    const WCHAR *got;
    int th, ta, td, il, el, ave, max, tmwt, oh, pf, tmcs;
} stock_row;

static void tm_compare(const char *src, HDC dc, const WCHAR *gotw, int th, int ta, int td, int il, int el, int ave, int max, int tmwt,
                       int oh, int pf, int tmcs){
    WCHAR got[LF_FACESIZE * 2] = L"";
    int n = U(GetTextFaceW)(dc, LF_FACESIZE * 2, got);
    CHECKF(n > 0 && !lstrcmpW(got, gotw), "%s: GetTextFace \"%ls\" want \"%ls\"", src, got, gotw);
    TEXTMETRICW tm; memset(&tm, 0, sizeof tm);
    CHECKF(U(GetTextMetricsW)(dc, &tm), "%s: GetTextMetricsW failed", src);
    CHECKF(tm.tmHeight == th, "%s: tmHeight %ld want %d", src, tm.tmHeight, th);
    CHECKF(tm.tmAscent == ta, "%s: tmAscent %ld want %d", src, tm.tmAscent, ta);
    CHECKF(tm.tmDescent == td, "%s: tmDescent %ld want %d", src, tm.tmDescent, td);
    CHECKF(tm.tmInternalLeading == il, "%s: tmInternalLeading %ld want %d", src, tm.tmInternalLeading, il);
    CHECKF(tm.tmExternalLeading == el, "%s: tmExternalLeading %ld want %d", src, tm.tmExternalLeading, el);
    CHECKF(tm.tmAveCharWidth == ave, "%s: tmAveCharWidth %ld want %d", src, tm.tmAveCharWidth, ave);
    CHECKF(tm.tmMaxCharWidth == max, "%s: tmMaxCharWidth %ld want %d", src, tm.tmMaxCharWidth, max);
    CHECKF(tm.tmWeight == tmwt, "%s: tmWeight %ld want %d", src, tm.tmWeight, tmwt);
    CHECKF(tm.tmOverhang == oh, "%s: tmOverhang %ld want %d", src, tm.tmOverhang, oh);
    CHECKF(tm.tmPitchAndFamily == pf, "%s: tmPitchAndFamily 0x%x want 0x%x", src, tm.tmPitchAndFamily, pf);
    CHECKF(tm.tmCharSet == tmcs, "%s: tmCharSet %d want %d", src, tm.tmCharSet, tmcs);
}
"""

