TEST(fr_addex_private_basic){ /* AddFontResourceExW FR_PRIVATE, RemoveFontResourceExW, fallback */
  REQUIRE(U(AddFontResourceExW)); REQUIRE(U(RemoveFontResourceExW));
  char face[64], path[MAX_PATH], g[96]; WCHAR wp[MAX_PATH]; face_name(face,sizeof face,"a");
  if(!write_font(face,"a.ttf",path,sizeof path)){ t_skip("cannot write scratch font"); return; } wide(wp,path);
  CHECK(!selects(face)); EXPECT_EQ(enum_count(face),0);
  int r=U(AddFontResourceExW)(wp,FR_PRIVATE,NULL); EXPECT_EQ(r,1);
  if(r!=1){ t_note("AddFontResourceExW returned %d, gle=%lu",r,GetLastError()); return; }
  CHECK(enum_count(face)>=1); CHECK(selects(face));
  sel_face(face,g,sizeof g); EXPECT_STR(g,face);
  EXPECT_EQ(U(RemoveFontResourceExW)(wp,FR_PRIVATE,NULL),TRUE);
  SET_ERR(0); BOOL again=U(RemoveFontResourceExW)(wp,FR_PRIVATE,NULL); EXPECT_EQ(again,FALSE);
  t_note("second RemoveFontResourceExW gle=%lu",GetLastError());
  EXPECT_EQ(enum_count(face),0); sel_face(face,g,sizeof g); CHECK(lstrcmpiA(g,face)!=0);
  t_note("fallback face after removal: \"%s\"",g);
}

