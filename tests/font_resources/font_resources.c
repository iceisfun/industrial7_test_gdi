TEST(fr_mem_resource){
  REQUIRE(U(AddFontMemResourceEx)); REQUIRE(U(RemoveFontMemResourceEx));
  char face[64]; BYTE buf[4096]; face_name(face,sizeof face,"m"); unsigned len=make_ttf(buf,face);
  CHECK(!selects(face)); DWORD n=0xdead; HANDLE h=U(AddFontMemResourceEx)(buf,len,NULL,&n);
  CHECK(h!=NULL); if(!h){ t_note("AddFontMemResourceEx failed gle=%lu",GetLastError()); return; }
  EXPECT_EQ(n,1); CHECK(selects(face)); t_note("memory font enumerated entries: %d",enum_count(face));
  DWORD c=t_run_child("fr_probe",face,XP_TMO); EXPECT_EQ(c,0);   /* private to this process */
  EXPECT_EQ(U(RemoveFontMemResourceEx)(h),TRUE);
  CHECK(!selects(face)); EXPECT_EQ(enum_count(face),0);
  SET_ERR(0); BOOL again=U(RemoveFontMemResourceEx)(h); EXPECT_EQ(again,FALSE);
  t_note("second RemoveFontMemResourceEx gle=%lu",GetLastError());
  /* two memory adds of the same bytes are independent handles */
  DWORD n1=0,n2=0; HANDLE h1=U(AddFontMemResourceEx)(buf,len,NULL,&n1), h2=U(AddFontMemResourceEx)(buf,len,NULL,&n2);
  CHECK(h1&&h2); CHECK(h1!=h2); EXPECT_EQ(n1,1); EXPECT_EQ(n2,1);
  if(h1) EXPECT_EQ(U(RemoveFontMemResourceEx)(h1),TRUE);
  if(h2){ CHECK(selects(face)); EXPECT_EQ(U(RemoveFontMemResourceEx)(h2),TRUE); }
  CHECK(!selects(face));
}

